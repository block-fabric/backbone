"""Compile src/grpc/proto/**/*.proto with protoc into the descriptor set that backboned embeds
(src/grpc/descriptors.cpp): its codec and its gRPC server reflection read it.

    contrib/devtools/gen-grpc-descriptors.py [--protoc PROTOC] [--include DIR]

DIR holds google/protobuf/{wrappers,timestamp}.proto (default /usr/include).

    contrib/devtools/gen-grpc-descriptors.py --compare ENFORCER_DIR

compares the definitions with those of a bip300301_enforcer checkout (its proto/ directory),
message by message, field by field: they must be the same but for Backbone's additions
(GetSeenBmmRequests, GenerateBlocks)."""
import argparse
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROTO = os.path.join(ROOT, 'src', 'grpc', 'proto')
OUT = os.path.join(ROOT, 'src', 'grpc', 'descriptors.cpp')


def protos(base, prefix=''):
    found = []
    for d, _, files in os.walk(os.path.join(base, prefix)):
        for f in files:
            if f.endswith('.proto'):
                found.append(os.path.relpath(os.path.join(d, f), base))
    return sorted(found)


def descriptor_set(protoc, include, base, files, imports):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'set.pb')
        cmd = [protoc, '-I' + base, '-I' + include, '--descriptor_set_out=' + out] + (['--include_imports'] if imports else []) + files
        subprocess.check_call(cmd)
        with open(out, 'rb') as f:
            return f.read()


def as_text(protoc, include, data):
    return subprocess.run([protoc, '-I' + include, '--decode=google.protobuf.FileDescriptorSet', 'google/protobuf/descriptor.proto'],
                          input=data, capture_output=True, check=True).stdout.decode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--protoc', default='protoc')
    parser.add_argument('--include', default='/usr/include')
    parser.add_argument('--compare')
    args = parser.parse_args()
    if args.compare:
        theirs = descriptor_set(args.protoc, args.include, os.path.join(args.compare, 'proto'), protos(os.path.join(args.compare, 'proto'), 'cusf'), False)
        ours = descriptor_set(args.protoc, args.include, PROTO, protos(PROTO, 'cusf'), False)
        a, b = as_text(args.protoc, args.include, theirs), as_text(args.protoc, args.include, ours)
        with tempfile.TemporaryDirectory() as tmp:
            pa, pb = os.path.join(tmp, 'enforcer.txt'), os.path.join(tmp, 'backbone.txt')
            open(pa, 'w').write(a)
            open(pb, 'w').write(b)
            diff = subprocess.run(['diff', pa, pb], capture_output=True, text=True).stdout
        removed = [l for l in diff.splitlines() if l.startswith('<')]
        added = [l for l in diff.splitlines() if l.startswith('>')]
        for name in ('GetSeenBmmRequests', 'GenerateBlocks'):
            if not any(name in l for l in added):
                print('missing addition', name)
                return 1
        if removed:
            print('\n'.join(removed))
            print('the definitions differ from the enforcer\'s')
            return 1
        print('same as the enforcer\'s, plus GetSeenBmmRequests and GenerateBlocks (%d lines of descriptor text added)' % len(added))
        return 0
    data = descriptor_set(args.protoc, args.include, PROTO, protos(PROTO), True)
    lines = []
    for i in range(0, len(data), 20):
        lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 20]) + ',')
    with open(OUT, 'w') as f:
        f.write('''// Copyright (c) 2026 The Backbone developers
// Distributed under the MIT software license, see the accompanying
// file COPYING or http://www.opensource.org/licenses/mit-license.php.

// Generated by contrib/devtools/gen-grpc-descriptors.py from src/grpc/proto: do not edit.

#include <grpc/descriptors.h>

namespace grpcsrv {

static const unsigned char DESCRIPTOR_SET[] = {
%s
};

std::span<const uint8_t> DescriptorSet() { return {DESCRIPTOR_SET, sizeof(DESCRIPTOR_SET)}; }

} // namespace grpcsrv
''' % '\n'.join(lines))
    print('wrote %s (%d bytes of descriptors)' % (OUT, len(data)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
